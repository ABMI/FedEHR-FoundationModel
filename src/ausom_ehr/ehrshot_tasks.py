"""Twelve EHRSHOT downstream tasks (5 lab abnormalities, 7 new diagnoses) on top of the tasks.py pipeline.

Stages: labels, inputs, embed (one GPU), logistic
Usage: python -m ausom_ehr.ehrshot_tasks <stage> --site SITE [--workers N] [--model state.pt] [--output DIR]
"""

from __future__ import annotations

import argparse
import json
from concurrent.futures import ProcessPoolExecutor
from datetime import timedelta
from pathlib import Path

import polars as pl

from ausom_ehr.common import RAW_ROOT, load_config, output_file, write_json
from ausom_ehr.tasks import make_visit, merge_admissions, process_input_bucket, summarize_inputs
from ausom_ehr.tokens import BUCKET_COUNT, context_limit, special_ids

PROJECT = Path(__file__).resolve().parents[2]
OUTPUTS = PROJECT / "outputs"
TASK_ROOT = OUTPUTS / "sites_disjoint" / "tasks_ehrshot"
SITES = ["A", "D0_random", "D1_pediatric", "D2_er", "D3_cancer", "D4_female", "D5_elderly"]

# MEASUREMENT.measurement_concept_id (LOINC); only the first concept of each list occurs in AUSOM.
LAB_CONCEPTS = {
    "plt": [3007461, 3024929],      # Platelets in Blood (26515-7), automated count (777-3)
    "k": [3005456, 3023103],        # Potassium in Blood (6298-4), in Serum or Plasma (2823-3)
    "glucose": [3037110, 3004501],  # Fasting glucose in Serum or Plasma (1558-6), Glucose (2345-7)
    "na": [3000285, 3019550],       # Sodium in Blood (2947-0), in Serum or Plasma (2951-2)
    "hb": [3000963],                # Hemoglobin in Blood (718-7)
}
LAB_TASKS = {  # task: (lab, comparison, threshold) in the target_unit of the units stage
    "ehrshot_thrombocytopenia": ("plt", "<", 150.0),   # 10^3/uL
    "ehrshot_hyperkalemia": ("k", ">", 5.5),           # mmol/L
    "ehrshot_hypoglycemia": ("glucose", "<", 70.0),    # mg/dL
    "ehrshot_hyponatremia": ("na", "<", 135.0),        # mmol/L
    "ehrshot_anemia": ("hb", "<", 12.0),               # g/dL
}
LAB_SAMPLE_LIMIT = 200_000
SAMPLE_SEED = 42
# SNOMED ancestor of CONDITION_OCCURRENCE.condition_concept_id; descendants come from CONCEPT_ANCESTOR.
NEWDX_TASKS = {
    "newdx_hypertension": 316866,     # Hypertensive disorder (SNOMED 38341003)
    "newdx_t2dm": 201826,             # Type 2 diabetes mellitus (44054006)
    "newdx_hyperlipidemia": 432867,   # Hyperlipidemia (55822004)
    "newdx_heart_failure": 316139,    # Heart failure (84114007)
    "newdx_ckd": 46271022,            # Chronic kidney disease (709044004)
    "newdx_ischemic_stroke": 443454,  # Cerebral infarction (432504007)
    "newdx_afib": 313217,             # Atrial fibrillation (49436004)
}
NEWDX_DAYS = 365
TASKS = list(LAB_TASKS) + list(NEWDX_TASKS)
CUTOFF_TASK = "ehrshot_cutoffs"
DOMAINS = ["condition", "drug", "procedure", "measurement", "observation"]
RUN_NAME = "epoch20"

POPULATION_CONFIG = """# Task-input config generated by ehrshot_tasks; not used for training.
[paths]
raw_root = "{raw_root}"
output_root = "{output_root}"
[tokenization]
mode = "concept_value_joint"
demographic_tokens = true
[model]
architecture = "gpt2"
"""


def site_roots(site: str) -> tuple[Path, Path, Path]:
    """(base preprocessing folder, joint-token model-input folder, patient split file) of a site."""
    if site == "A":
        return OUTPUTS / "base", OUTPUTS / "m0", OUTPUTS / "base" / "sample" / "selected_patients.parquet"
    root = OUTPUTS / "sites_disjoint" / site
    return root / "base", root / "joint", OUTPUTS / "sites_disjoint" / f"{site}.parquet"


def link(target: Path, link_path: Path) -> None:
    """Symlink link_path to target; raise if a different link or a real file is already there."""
    if not target.exists():
        raise FileNotFoundError(target)
    if link_path.is_symlink():
        if link_path.resolve() != target.resolve():
            raise ValueError(f"linked to a different target: {link_path}")
        return
    if link_path.exists():
        raise FileExistsError(link_path)
    link_path.parent.mkdir(parents=True, exist_ok=True)
    link_path.symlink_to(target, target_is_directory=target.is_dir())


def load_people(base: Path, patient_file: Path) -> pl.DataFrame:
    """Per-patient split, last record date and earliest death date."""
    persons = pl.read_parquet(patient_file).select(pl.col("person_id").cast(pl.Int64), "split")
    record_end = pl.read_parquet(base / "cohorts" / "record_end.parquet")
    death = (
        pl.read_parquet(base / "cohorts" / "death.parquet")
        .select("person_id", pl.col("death_date").str.slice(0, 10).str.to_date(strict=False).alias("death"))
        .drop_nulls("death")
        .group_by("person_id").agg(pl.col("death").min())
    )
    return persons.join(record_end, on="person_id", how="left").join(death, on="person_id", how="left")


def first_event_dates(base: Path) -> pl.DataFrame:
    """First model-input event date per patient (mapped, not held); used only to pre-filter empty histories."""
    return (
        pl.concat([
            pl.scan_parquet(base / "events" / f"{domain}.parquet")
            .filter((pl.col("concept_id") > 0) & pl.col("event_hold_reason").is_null())
            .select("person_id", "event_date")
            for domain in DOMAINS
        ])
        .group_by("person_id").agg(pl.col("event_date").min().alias("first_event"))
        .collect()
    )


def sample_rows(rows: pl.DataFrame, limit: int) -> pl.DataFrame:
    """Keep `limit` rows in (patient, cutoff) hash order, so a day ranks the same in every lab task."""
    if rows.height <= limit:
        return rows
    return (
        rows.with_columns(pl.struct("person_id", "cutoff_date").hash(seed=SAMPLE_SEED).alias("_key"))
        .sort("_key", "person_id", "cutoff_date")
        .head(limit)
        .drop("_key")
    )


def lab_labels(base: Path, people: pl.DataFrame, first_event: pl.DataFrame) -> tuple[pl.DataFrame, dict]:
    """Samples and audit counts for the 5 lab tasks.

    One sample per (patient, test day) with cutoff 23:59 the day before; positive if any result that day is abnormal.
    """
    concept_to_lab = {concept: lab for lab, concepts in LAB_CONCEPTS.items() for concept in concepts}
    raw = (
        pl.scan_parquet(base / "units" / "measurement.parquet")
        .filter(pl.col("concept_id").is_in(list(concept_to_lab)))
        .select("person_id", "concept_id", "event_date", "numeric_value", "event_hold_reason", "target_unit", "unit_status")
        .collect()
    )
    audit = {
        "rows_by_concept_unit_status": (
            raw.group_by("concept_id", "target_unit", "unit_status")
            .agg(pl.len().alias("rows"), pl.col("numeric_value").is_null().sum().alias("no_numeric_value"),
                 pl.col("event_hold_reason").is_not_null().sum().alias("held"))
            .sort("concept_id", "unit_status").to_dicts()
        ),
    }
    measurements = (
        raw.filter(pl.col("numeric_value").is_not_null() & pl.col("event_hold_reason").is_null())
        .with_columns(pl.col("concept_id").replace_strict(concept_to_lab, return_dtype=pl.String).alias("lab"))
    )
    frames = []
    for task, (lab, op, threshold) in LAB_TASKS.items():
        abnormal = (pl.col("numeric_value") > threshold) if op == ">" else (pl.col("numeric_value") < threshold)
        days = (
            measurements.filter(pl.col("lab") == lab)
            .group_by("person_id", "event_date")
            .agg(abnormal.any().cast(pl.Int8).alias("label"), pl.len().alias("results"))
            .with_columns((pl.col("event_date") - pl.duration(days=1)).alias("cutoff_date"))
            .join(people, on="person_id", how="inner")
            .join(first_event, on="person_id", how="left")
        )
        counts = {"lab_days": days.height, "lab_days_with_multiple_results": days.filter(pl.col("results") > 1).height}
        days = days.filter(pl.col("death").is_null() | (pl.col("death") > pl.col("cutoff_date")))
        counts["after_death_rule"] = days.height
        days = days.filter(pl.col("first_event").is_not_null() & (pl.col("first_event") <= pl.col("cutoff_date")))
        counts["with_history_before_cutoff"] = days.height
        days = sample_rows(days, LAB_SAMPLE_LIMIT)
        counts["sampled"] = days.height
        audit[task] = counts
        frames.append(days.select(
            "person_id", "split", pl.lit(task).alias("task"), "cutoff_date",
            (pl.col("cutoff_date").cast(pl.String) + "T23:59:00").alias("index_datetime"),
            pl.lit(None, dtype=pl.Int64).alias("index_visit_id"), "label",
            pl.when(pl.col("label") == 1).then(pl.lit("abnormal_result_that_day"))
            .otherwise(pl.lit("all_results_normal_that_day")).alias("label_reason"),
            pl.lit(1, dtype=pl.Int16).alias("result_window_days"), "last_record_date",
        ))
    return pl.concat(frames), audit


def discharge_episodes(base: Path) -> tuple[pl.DataFrame, dict]:
    """Discharge date (cutoff), discharge time and last visit ID of each merged admission."""
    visits = (
        pl.read_parquet(
            base / "cohorts" / "visits.parquet",
            columns=["person_id", "split", "visit_occurrence_id", "visit_concept_id",
                     "visit_start_datetime", "visit_end_datetime"],
        )
        .sort("person_id", "visit_start_datetime", "visit_occurrence_id")
    )
    rows = []
    current, patient_visits = None, []

    def finish() -> None:
        for episode in merge_admissions(patient_visits):
            rows.append({
                "person_id": current, "cutoff_date": episode["end"].date(),
                "index_datetime": episode["end"].isoformat(), "index_visit_id": episode["terminal_visit_id"],
            })

    for row in visits.iter_rows():
        if row[0] != current:
            if patient_visits:
                finish()
            current, patient_visits = row[0], []
        patient_visits.append(make_visit(row))
    if patient_visits:
        finish()
    episodes = pl.DataFrame(rows, schema={"person_id": pl.Int64, "cutoff_date": pl.Date,
                                          "index_datetime": pl.String, "index_visit_id": pl.Int64})
    # Episodes ending on the same day share input and labels; keep the last discharge.
    deduplicated = episodes.sort("person_id", "cutoff_date", "index_datetime").unique(
        ["person_id", "cutoff_date"], keep="last", maintain_order=True)
    return deduplicated, {"merged_episodes": episodes.height, "same_day_discharges_dropped": episodes.height - deduplicated.height}


def descendant_map(raw_root: Path) -> pl.DataFrame:
    """Ancestor to descendant concept table (descendants include the ancestor itself)."""
    return (
        pl.scan_parquet(raw_root / "dbo" / "CONCEPT_ANCESTOR" / "**" / "*.parquet")
        .filter(pl.col("ancestor_concept_id").cast(pl.Int64).is_in(list(NEWDX_TASKS.values())))
        .select(pl.col("ancestor_concept_id").cast(pl.Int64).alias("ancestor"),
                pl.col("descendant_concept_id").cast(pl.Int64).alias("concept_id"))
        .collect()
    )


def newdx_labels(base: Path, people: pl.DataFrame, raw_root: Path) -> tuple[pl.DataFrame, dict]:
    """Samples and audit counts for the 7 new-diagnosis tasks.

    Discharges without the diagnosis so far; positive if first diagnosed within NEWDX_DAYS, censored like readmit30.
    """
    episodes, audit = discharge_episodes(base)
    ancestors = descendant_map(raw_root)
    conditions = (
        pl.scan_parquet(base / "events" / "condition.parquet")
        .filter(pl.col("event_hold_reason").is_null())
        .select("person_id", "concept_id", "event_date")
        .collect()
        .join(ancestors, on="concept_id", how="inner")
    )
    audit["condition_rows_by_ancestor"] = (
        conditions.group_by("ancestor").agg(pl.len().alias("rows"), pl.col("concept_id").n_unique().alias("concepts_used"))
        .join(ancestors.group_by("ancestor").agg(pl.len().alias("concepts_in_hierarchy")), on="ancestor", how="right")
        .sort("ancestor").to_dicts()
    )
    first_dx = conditions.group_by("person_id", "ancestor").agg(pl.col("event_date").min().alias("first_dx"))
    base_rows = episodes.join(people, on="person_id", how="inner")
    horizon = pl.col("cutoff_date") + pl.duration(days=NEWDX_DAYS)
    frames = []
    for task, ancestor in NEWDX_TASKS.items():
        rows = base_rows.join(
            first_dx.filter(pl.col("ancestor") == ancestor).select("person_id", "first_dx"), on="person_id", how="left")
        counts = {"discharges": rows.height}
        rows = rows.filter(pl.col("death").is_null() | (pl.col("death") > pl.col("cutoff_date")))
        counts["alive_after_discharge"] = rows.height
        rows = rows.filter(pl.col("first_dx").is_null() | (pl.col("first_dx") > pl.col("cutoff_date")))
        counts["no_diagnosis_by_discharge"] = rows.height
        rows = rows.with_columns(
            pl.when(pl.col("first_dx").is_not_null() & (pl.col("first_dx") <= horizon)).then(pl.lit(1))
            .when((pl.col("last_record_date") >= horizon) & (pl.col("death").is_null() | (pl.col("death") > horizon))).then(pl.lit(0))
            .otherwise(None).cast(pl.Int8).alias("label"),
        )
        counts["positive"] = rows.filter(pl.col("label") == 1).height
        counts["negative"] = rows.filter(pl.col("label") == 0).height
        counts["unlabeled_short_follow_up_or_death"] = rows.filter(pl.col("label").is_null()).height
        audit[task] = counts
        frames.append(rows.filter(pl.col("label").is_not_null()).select(
            "person_id", "split", pl.lit(task).alias("task"), "cutoff_date", "index_datetime", "index_visit_id", "label",
            pl.when(pl.col("label") == 1).then(pl.lit("first_diagnosis_within_365d"))
            .otherwise(pl.lit("no_diagnosis_followed_365d")).alias("label_reason"),
            pl.lit(NEWDX_DAYS, dtype=pl.Int16).alias("result_window_days"), "last_record_date",
        ))
    return pl.concat(frames), audit


def task_counts(labels: pl.DataFrame) -> list[dict]:
    return (
        labels.group_by("task", "split")
        .agg(pl.len().alias("samples"), pl.col("person_id").n_unique().alias("patients"),
             pl.col("label").cast(pl.Int64).sum().alias("positives"),
             pl.col("person_id").filter(pl.col("label") == 1).n_unique().alias("positive_patients"))
        .sort("task", "split").to_dicts()
    )


def run_labels(site: str) -> None:
    base, model_root, patient_file = site_roots(site)
    root = TASK_ROOT / site
    destination = root / "cohorts" / "task_labels.parquet"
    if destination.exists():
        raise FileExistsError(destination)
    people = load_people(base, patient_file)
    labs, lab_audit = lab_labels(base, people, first_event_dates(base))
    newdx, newdx_audit = newdx_labels(base, people, RAW_ROOT)
    labels = pl.concat([labs, newdx]).with_columns(pl.col("label").cast(pl.Int8))
    destination.parent.mkdir(parents=True, exist_ok=True)
    labels.sort("task", "person_id", "cutoff_date").write_parquet(destination, compression="zstd")
    # One input candidate per (patient, cutoff); label 0 is an unused placeholder the input code requires.
    cutoffs = (
        labels.select("person_id", "split", "cutoff_date").unique()
        .with_columns(
            pl.lit(CUTOFF_TASK).alias("task"),
            (pl.col("cutoff_date").cast(pl.String) + "T23:59:00").alias("index_datetime"),
            pl.lit(None, dtype=pl.Int64).alias("index_visit_id"), pl.lit(0, dtype=pl.Int8).alias("label"),
            pl.lit("cutoff_only").alias("label_reason"), pl.lit(None, dtype=pl.Int16).alias("result_window_days"),
            pl.lit(None, dtype=pl.Date).alias("last_record_date"),
        )
        .select("person_id", "split", "task", "cutoff_date", "index_datetime", "index_visit_id", "label",
                "label_reason", "result_window_days", "last_record_date")
        .sort("person_id", "cutoff_date")
    )
    if cutoffs.select(pl.struct("person_id", "cutoff_date").n_unique()).item() != cutoffs.height:
        raise ValueError("a (patient, cutoff) pair has more than one split")
    cutoffs.write_parquet(root / "cohorts" / "candidates.parquet", compression="zstd")
    link(model_root / "tokens", root / "tokens")
    link(model_root / "demographics", root / "demographics")
    link(model_root / "cohorts" / "visits.parquet", root / "cohorts" / "visits.parquet")
    (root / "population.toml").write_text(POPULATION_CONFIG.format(raw_root=RAW_ROOT, output_root=root))
    write_json(root / "cohorts" / "labels_summary.json", {
        "site": site, "base": str(base), "model_inputs_from": str(model_root),
        "lab_sample_limit": LAB_SAMPLE_LIMIT, "sample_seed": SAMPLE_SEED, "polars_version": pl.__version__,
        "lab_concepts": LAB_CONCEPTS, "lab_tasks": LAB_TASKS, "newdx_ancestors": NEWDX_TASKS, "newdx_days": NEWDX_DAYS,
        "unique_cutoffs": cutoffs.height,
        "lab_audit": lab_audit, "newdx_audit": newdx_audit,
        "samples_by_task_split": task_counts(labels),
    })
    print(f"{site}: {labels.height:,} task samples, {cutoffs.height:,} cutoffs", flush=True)


def _input_bucket(job: tuple[str, int]) -> tuple[Path, dict]:
    config_path, bucket = job
    config = load_config(config_path)
    ids = special_ids(output_file(config, "tokens", "vocab.parquet"))
    return process_input_bucket(config, bucket, ids)


def run_inputs(site: str, workers: int) -> None:
    """Same as tasks.run_inputs with buckets in parallel."""
    config_path = str(TASK_ROOT / site / "population.toml")
    config = load_config(config_path)
    context_limit(config)
    with ProcessPoolExecutor(workers) as pool:
        results = list(pool.map(_input_bucket, [(config_path, bucket) for bucket in range(BUCKET_COUNT)]))
    totals: dict[tuple[str, str], dict[str, int]] = {}
    exception_paths = []
    for _path, audit in results:
        for row in audit["by_task_split"]:
            if row.get("oversized_latest_day_samples", 0):
                exception_paths.append(audit["exception_path"])
            counts = totals.setdefault((row["task"], row["split"]), {})
            for key, value in row.items():
                if key not in {"task", "split"}:
                    counts[key] = counts.get(key, 0) + value
    split_rows = [{"task": task, "split": split, **counts} for (task, split), counts in sorted(totals.items())]
    summarize_inputs(config, split_rows, sorted(set(exception_paths)))


def run_embed_stage(site: str, model: Path, output: Path) -> None:
    from ausom_ehr.evaluate import run_embed
    from ausom_ehr.federated import prepare_eval
    config_path = prepare_eval(model, (TASK_ROOT / site).resolve(), output, RAW_ROOT)
    run_embed(str(config_path), [CUTOFF_TASK], "continued", RUN_NAME)


def run_logistic_stage(site: str, output: Path) -> None:
    """Attach task labels to cutoff embeddings, run evaluate.run_logistic and save test probabilities."""
    import joblib
    import numpy as np
    from ausom_ehr.evaluate import run_logistic
    from sklearn.metrics import roc_auc_score

    config_path = str(output / "eval_config.toml")
    embeddings_dir = output / "embeddings" / "continued" / RUN_NAME
    vectors = pl.read_parquet(embeddings_dir / f"{CUTOFF_TASK}.parquet").select(
        "person_id", pl.col("split").alias("embedding_split"), "cutoff_date", "embedding")
    labels = pl.read_parquet(TASK_ROOT / site / "cohorts" / "task_labels.parquet")
    coverage = []
    for task in TASKS:
        part = labels.filter(pl.col("task") == task)
        joined = part.join(vectors, on=["person_id", "cutoff_date"], how="inner")
        if (joined["split"] != joined["embedding_split"]).any():
            raise ValueError(f"{task}: label and embedding splits differ")
        coverage.append({"task": task, "labeled": part.height, "with_input": joined.height,
                         "dropped_no_history_or_oversized": part.height - joined.height})
        joined.select("person_id", "split", "label", "index_visit_id", "cutoff_date", "embedding").write_parquet(
            embeddings_dir / f"{task}.parquet", compression="zstd")
    del vectors
    run_logistic(config_path, TASKS, "continued", RUN_NAME)
    evaluation_dir = output / "evaluation" / "continued" / RUN_NAME
    results = {row["task"]: row for row in json.loads((evaluation_dir / "results.json").read_text())["tasks"]}
    predictions = []
    for task in TASKS:
        data = pl.read_parquet(embeddings_dir / f"{task}.parquet").filter(pl.col("split") == "test")
        model = joblib.load(evaluation_dir / f"{task}_model.joblib")
        probability = model.predict_proba(np.asarray(data["embedding"].to_list(), dtype=np.float32))[:, 1]
        auroc = roc_auc_score(data["label"].to_numpy(), probability)
        if abs(auroc - results[task]["test"]["auroc"]) > 1e-9:
            raise ValueError(f"{task}: recomputed test AUROC differs from results.json")
        predictions.append(data.select(pl.lit(task).alias("task"), "person_id", "cutoff_date", "index_visit_id", "label")
                           .with_columns(pl.Series("probability", probability)))
    pl.concat(predictions).write_parquet(evaluation_dir / "test_predictions.parquet", compression="zstd")
    write_json(evaluation_dir / "coverage.json", {"tasks": coverage})


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    stages = parser.add_subparsers(dest="stage", required=True)
    for name in ["labels", "inputs", "embed", "logistic"]:
        stage = stages.add_parser(name)
        stage.add_argument("--site", required=True, choices=SITES)
        if name == "inputs":
            stage.add_argument("--workers", type=int, default=16)
        if name in {"embed", "logistic"}:
            stage.add_argument("--output", required=True, type=Path)
        if name == "embed":
            stage.add_argument("--model", required=True, type=Path)
    args = parser.parse_args()
    if args.stage == "labels":
        run_labels(args.site)
    elif args.stage == "inputs":
        run_inputs(args.site, args.workers)
    elif args.stage == "embed":
        run_embed_stage(args.site, args.model, args.output)
    else:
        run_logistic_stage(args.site, args.output)


if __name__ == "__main__":
    main()
